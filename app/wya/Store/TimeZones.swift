    /// the zone for a place: its country's nearest zone (by its lat/lon), or the country's first one
    static func zone(cc: String?, lat: Double? = nil, lon: Double? = nil) -> String? {
        guard let cc = cc?.lowercased() else { return nil }
        // only the zones this phone knows (tzdata adds zones before every system has them: America/Coyhaique, 2025)
        let cand = zones.filter { $0.cc == cc && TimeZone(identifier: $0.tz) != nil }
        guard let first = cand.first else { return nil }
        guard let lat, let lon, cand.count > 1 else { return main[cc] ?? first.tz }
        func d(_ z: (cc: String, lat: Double, lon: Double, tz: String)) -> Double {
            let k = cos(lat * .pi / 180)
            return pow(z.lat - lat, 2) + pow((z.lon - lon) * k, 2)
        }
        return cand.min { d($0) < d($1) }?.tz
    }
